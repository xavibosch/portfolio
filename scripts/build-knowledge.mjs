// Builds api/_knowledge.js: every fact the assistant may use, cut into
// small titled pieces. Sources are the same files the site renders from, so
// the assistant cannot know more (or less) than the portfolio says.
//   node scripts/build-knowledge.mjs
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const projects = JSON.parse(await readFile(new URL('src/projects.json', root)));
const { caseStudies, SECTIONS } = await import(new URL('src/case-studies.js', root));
const profile = await readFile(new URL('content/bot/profile.md', root), 'utf8');

const chunks = [];
const clean = text => String(text || '')
  .replace(/\[Cal [^\]]*\]/g, '').replace(/SENSE PROVA VISUAL REAL\.?/g, '')
  .replace(/\[TODO:[^\]]*\]/g, '').replace(/\s+/g, ' ').trim();
const add = (title, text, link) => { const body = clean(text); if (body) chunks.push({ title, text: body, link }); };

// The hand-written profile: one piece per "## " heading.
for (const block of profile.split(/^## /m).slice(1)) {
  const [title, ...lines] = block.split('\n');
  add(`About Xavi: ${title.trim()}`, lines.join(' '), '#/about');
}

const STATUS = { known: 'Known', observed: 'Observed', assumed: 'Assumed (not proven)', tested: 'Tested', validated: 'Validated', 'not-validated': 'Not validated yet', planned: 'Planned, not done yet' };
const blockText = b => {
  switch (b.type) {
    case 'text': return b.paragraphs.join(' ');
    case 'claims': return b.items.map(([s, t]) => `[${STATUS[s]}] ${t}`).join(' ');
    case 'options': return b.items.map(o => `Alternative "${o.title}" (${o.verdict}): trying to solve ${o.solving} For it: ${o.pros} Against it: ${o.cons} What happened: ${o.why}`).join(' ');
    case 'decision': return `Central decision "${b.title}". Situation: ${b.situation} Options considered: ${b.options.join(' / ')} Decision: ${b.decision} Reasoning: ${b.reasoning} Trade-off: ${b.tradeoff} Consequence: ${b.consequence}`;
    case 'stack': return b.items.map(([n, w]) => `${n}: ${w}`).join(' ');
    case 'checks': return b.items.map(([s, t]) => `[${s === 'done' ? 'Done' : s === 'reviewed' ? 'Reviewed' : 'Still to do'}] ${t}`).join(' ');
    case 'testPlan': return `Not tested yet. What Xavi would test next: participants ${b.participants} Tasks: ${b.tasks.join(' ')} Success would look like: ${b.success.join(' ')}`;
    case 'media': case 'gallery': {
      const items = b.type === 'media' ? [b.item] : b.items;
      return items.filter(i => i.kind !== 'placeholder').map(i => `Image: ${i.caption}.`).join(' ');
    }
    default: return ''; // editing notes are never knowledge
  }
};

for (const p of projects) {
  const link = `#/work/${p.slug}`;
  add(`${p.name}: overview`, `${p.name} is a ${p.featured ? 'main case study' : p.category.toLowerCase()} in Xavi's portfolio. ${p.summary} ${p.tagline} Status: ${p.status}. Built: ${clean(p.team) || 'not stated'}. Xavi's role: ${p.role}. It shows: ${p.capability}. Technologies: ${p.tech.join(', ')}.${p.live ? ` Live at ${p.live}.` : ''}${p.repo ? ` Source code: ${p.repo}.` : ''}`, link);
  add(`${p.name}: problem, decision and lesson`, `The problem: ${p.card.problem} The decision: ${p.card.decision} What Xavi learned: ${p.card.learned}`, link);
  if (!caseStudies[p.slug]) {
    add(`${p.name}: the full story`, `Who it is for: ${p.builtFor} ${p.problem} What it does: ${p.description} What changed along the way: ${p.changed} ${p.research ? `Research: ${p.research}` : ''} What he learned: ${p.learning} ${clean(p.pending) ? `Still open: ${clean(p.pending)}` : ''}`, link);
  }
}

for (const [slug, cs] of Object.entries(caseStudies)) {
  const p = projects.find(x => x.slug === slug);
  add(`${p.name} case study: facts`, `${cs.oneLiner} Role: ${cs.role}. Type: ${cs.type}. Team: ${cs.team}. ${cs.timeline ? `Timeline: ${cs.timeline}.` : 'The timeline is not stated in the portfolio.'} Status: ${cs.status}. Built with: ${cs.stack.join(', ')}.`, `#/work/${slug}`);
  for (const [id, title] of SECTIONS) {
    add(`${p.name} case study: ${title}`, (cs.sections[id] || []).map(blockText).join(' '), `#/work/${slug}`);
  }
}

await writeFile(new URL('api/_knowledge.js', root), `// Generated by scripts/build-knowledge.mjs. Do not edit by hand.\nexport default ${JSON.stringify(chunks, null, 1)};\n`);
const words = chunks.reduce((n, c) => n + c.text.split(' ').length, 0);
console.log(`${chunks.length} pieces, ${words} words`);
